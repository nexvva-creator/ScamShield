from __future__ import annotations

import sqlite3
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterator

from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


class Database:
    def __init__(self, database: str | Path) -> None:
        database_value = str(database)
        self.pool: ConnectionPool | None = None
        self.path: Path | None = None

        if database_value.startswith(("postgres://", "postgresql://")):
            self.pool = ConnectionPool(
                conninfo=database_value,
                min_size=1,
                max_size=5,
                timeout=10,
                kwargs={"row_factory": dict_row, "prepare_threshold": None},
                open=True,
            )
        else:
            self.path = Path(database_value)
            self.path.parent.mkdir(parents=True, exist_ok=True)

        self._initialize()

    @contextmanager
    def _connect(self) -> Iterator[Any]:
        if self.pool is not None:
            with self.pool.connection() as connection:
                yield connection
            return

        if self.path is None:
            raise RuntimeError("The database is not configured.")
        connection = sqlite3.connect(self.path, timeout=5)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys = ON")
        try:
            yield connection
            connection.commit()
        except BaseException:
            connection.rollback()
            raise
        finally:
            connection.close()

    def _initialize(self) -> None:
        with self._connect() as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS reports (
                    id TEXT PRIMARY KEY,
                    reference TEXT NOT NULL UNIQUE,
                    category TEXT NOT NULL,
                    target TEXT NOT NULL,
                    summary TEXT NOT NULL,
                    status TEXT NOT NULL CHECK (status IN ('pending', 'verified', 'rejected', 'escalated')),
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                )
                """
            )
            connection.execute(
                "CREATE INDEX IF NOT EXISTS reports_status_created ON reports(status, created_at)"
            )
            audit_id = (
                "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
                if self.pool is not None
                else "INTEGER PRIMARY KEY AUTOINCREMENT"
            )
            connection.execute(
                f"""
                CREATE TABLE IF NOT EXISTS audit_log (
                    id {audit_id},
                    report_id TEXT NOT NULL,
                    action TEXT NOT NULL,
                    reason TEXT NOT NULL,
                    created_at TEXT NOT NULL,
                    FOREIGN KEY(report_id) REFERENCES reports(id)
                )
                """
            )

    def _execute(self, connection: Any, statement: str, parameters: tuple[object, ...] = ()) -> Any:
        if self.pool is not None:
            statement = statement.replace("?", "%s")
        return connection.execute(statement, parameters)

    def create_report(self, report_id: str, reference: str, category: str, target: str, summary: str) -> None:
        now = _now()
        with self._connect() as connection:
            self._execute(
                connection,
                "INSERT INTO reports (id, reference, category, target, summary, status, created_at, updated_at) VALUES (?, ?, ?, ?, ?, 'pending', ?, ?)",
                (report_id, reference, category, target, summary, now, now),
            )

    def get_report_by_token(self, reference: str) -> sqlite3.Row | dict[str, str] | None:
        with self._connect() as connection:
            return self._execute(
                connection,
                "SELECT reference, status, updated_at FROM reports WHERE reference = ?",
                (reference,),
            ).fetchone()

    def pending_reports(self) -> list[dict[str, str]]:
        with self._connect() as connection:
            rows = self._execute(
                connection,
                "SELECT id, category, target, summary, status, created_at FROM reports WHERE status = 'pending' ORDER BY created_at ASC",
            ).fetchall()
            return [dict(row) for row in rows]

    def review_report(self, report_id: str, status: str, reason: str) -> bool:
        now = _now()
        with self._connect() as connection:
            cursor = self._execute(
                connection,
                "UPDATE reports SET status = ?, updated_at = ? WHERE id = ? AND status = 'pending'",
                (status, now, report_id),
            )
            if cursor.rowcount != 1:
                return False
            self._execute(
                connection,
                "INSERT INTO audit_log (report_id, action, reason, created_at) VALUES (?, ?, ?, ?)",
                (report_id, status, reason, now),
            )
            return True

    def close(self) -> None:
        if self.pool is not None:
            self.pool.close()
